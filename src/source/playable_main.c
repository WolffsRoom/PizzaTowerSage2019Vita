static Instance* pizza_find_active_instance(Runner* runner, const char* objectName) {
    if (runner == NULL || objectName == NULL || runner->assetsByName == NULL) return NULL;
    int mapIndex = shgeti(runner->assetsByName, objectName);
    if (mapIndex < 0) return NULL;
    int32_t objectIndex = runner->assetsByName[mapIndex].value;
    if (objectIndex < 0 || (uint32_t)objectIndex >= runner->dataWin->objt.count) return NULL;
    Instance** bucket = runner->instancesByExactObject[objectIndex];
    for (ptrdiff_t i = 0; i < arrlen(bucket); ++i) {
        Instance* inst = bucket[i];
        if (inst != NULL && inst->active && !inst->destroyed) return inst;
    }
    return NULL;
}

static bool pizza_set_bool_var(Runner* runner, Instance* inst, const char* name, bool value) {
    if (runner == NULL || runner->vmContext == NULL || inst == NULL || name == NULL) return false;
    ptrdiff_t mapIndex = shgeti(runner->vmContext->varNameMap, (char*)name);
    if (mapIndex < 0) return false;
    int32_t varId = runner->vmContext->varNameMap[mapIndex].value;
    Instance_setSelfVar(inst, varId, RValue_makeBool(value));
    return true;
}

