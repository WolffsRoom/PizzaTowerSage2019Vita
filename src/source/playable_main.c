static SceUID probe_log_fd = -1;
void PizzaVita_logLine(const char *text) {
    char line[1024];
    int length=snprintf(line,sizeof(line),"%s\n",text);
    if (probe_log_fd < 0)
        probe_log_fd = sceIoOpen(LOG_PATH, SCE_O_WRONLY | SCE_O_CREAT | SCE_O_APPEND, 0666);
    if (probe_log_fd >= 0 && length > 0) {
        /* Other subsystems append through libc; refresh this persistent
         * descriptor's position before writing (also required by Vita3K). */
        sceIoLseek(probe_log_fd,0,SCE_SEEK_END);
        int written = sceIoWrite(probe_log_fd,line,(unsigned)(length<(int)sizeof(line)?length:(int)sizeof(line)-1));
        if (written < 0) { sceIoClose(probe_log_fd); probe_log_fd = -1; }
    }
}
