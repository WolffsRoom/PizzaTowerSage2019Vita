static int pizza_read_int_var(Runner* runner, Instance* inst, const char* varName, bool* found) {
    if (found != NULL) *found = false;
    if (runner == NULL || inst == NULL || varName == NULL || runner->vmContext == NULL) return 0;
    int mapIndex = shgeti(runner->vmContext->varNameMap, (char*)varName);
    if (mapIndex < 0) return 0;
    int32_t varId = runner->vmContext->varNameMap[mapIndex].value;
    RValue value = Instance_getSelfVar(inst, varId);
    if (value.type == RVALUE_UNDEFINED) return 0;
    if (found != NULL) *found = true;
    return RValue_toInt32(value);
}
static int pizza_read_bool_var(Runner* runner, Instance* inst, const char* varName, bool* found) {
    if (found != NULL) *found = false;
    if (runner == NULL || inst == NULL || varName == NULL || runner->vmContext == NULL) return 0;
    int mapIndex = shgeti(runner->vmContext->varNameMap, varName);
    if (mapIndex < 0) return 0;
    int32_t varId = runner->vmContext->varNameMap[mapIndex].value;
    RValue value = Instance_getSelfVar(inst, varId);
    if (value.type == RVALUE_UNDEFINED) return 0;
    if (found != NULL) *found = true;
    return RValue_toBool(value) ? 1 : 0;
}

