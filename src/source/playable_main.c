    uint32_t pause_previous_buttons = 0;
    bool f5_was_down = false;
    PizzaVitaQualityChordState quality_chord = {0};
    int pending_quality_delta = 0;
#ifdef PIZZA_MODERN_GL
    GLRenderer_requestTextureQuality((GLRenderer*)renderer,
        PIZZA_TEXTURE_QUALITY_HIGH);
#endif
    uint32_t frame = 0;
    uint64_t last_time = sceKernelGetProcessTimeWide();
    VitaFramePacer frame_pacer;
    VitaFramePacer_init(&frame_pacer, 60, last_time);
    bool exit_requested = false;
    int logged_game_w = -1;
    int logged_game_h = -1;
    int logged_room_index = -999;
    uint64_t perf_window_start = last_time;
    uint64_t perf_work_total_us = 0, perf_wait_total_us = 0;
    uint64_t perf_frame_total_us = 0, perf_max_us = 0;
    uint32_t perf_frames = 0, perf_drops = 0, perf_severe = 0;
    /* Per-phase averages for ordinary frames: PERF_SLOW only shows spikes,
     * not where a steady 33 ms frame goes. */
    uint64_t perf_step_us = 0, perf_world_us = 0, perf_gui_us = 0, perf_present_us = 0, perf_audio_us = 0, perf_prepare_us = 0;
