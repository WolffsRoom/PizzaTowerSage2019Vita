                VitaSettings_setGraphicsQuality(&settings, (int)next);
#ifdef PIZZA_MODERN_GL
                GLRenderer_requestTextureQuality((GLRenderer*)renderer, PIZZA_TEXTURE_QUALITY_HIGH);
#endif
