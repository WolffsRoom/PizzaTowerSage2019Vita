            const char* spriteName = dw->sprt.sprites[activePlayer->spriteIndex].name;
            if (spriteName && strncmp(spriteName, "spr_playerN_", 12) == 0) {
                selectedCharacter = 1; characterKnown = true;
            } else if (spriteName && strncmp(spriteName, "spr_player_", 11) == 0) {
                selectedCharacter = 0; characterKnown = true;
            }
