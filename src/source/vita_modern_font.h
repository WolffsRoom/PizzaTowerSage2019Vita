static inline uint32_t vita_utf8_next(const char** p) {
    const unsigned char* s = (const unsigned char*)(*p);
    if (*s == 0) return 0;
    if (*s < 0x80) { (*p)++; return *s; }
    if ((s[0] & 0xE0) == 0xC0 && s[1]) { uint32_t cp = ((s[0] & 0x1F) << 6) | (s[1] & 0x3F); (*p) += 2; return cp; }
    if ((s[0] & 0xF0) == 0xE0 && s[1] && s[2]) { uint32_t cp = ((s[0] & 0x0F) << 12) | ((s[1] & 0x3F) << 6) | (s[2] & 0x3F); (*p) += 3; return cp; }
    (*p)++; return '?';
}

